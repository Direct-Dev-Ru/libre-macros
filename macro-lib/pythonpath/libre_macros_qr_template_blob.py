def qr_template_ods_bytes():
    return base64.b64decode(QR_TEMPLATE_ODS_B64.encode("ascii"))


def write_qr_template_ods(path):
    data = qr_template_ods_bytes()
    path = os.path.abspath(str(path))
    parent = os.path.dirname(path)
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with open(path, "wb") as f:
        f.write(data)
    return path
