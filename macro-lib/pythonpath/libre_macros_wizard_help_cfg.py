def lookup_fn_help(key):
    """Вернуть развёрнутую справку или u''."""
    k = unicode(key or u"").strip()
    if k == u"":
        return u""
    try:
        k_cf = k.casefold()
    except Exception:
        k_cf = k.lower()
    canon = None
    for ak, av in _FN_HELP_ALIASES.items():
        if unicode(ak).casefold() == k_cf:
            canon = av
            break
    if canon is None:
        canon = k
    text = _FN_HELP_TEXTS.get(canon)
    if text is None:
        for hk, hv in _FN_HELP_TEXTS.items():
            try:
                if unicode(hk).casefold() == unicode(canon).casefold():
                    text = hv
                    break
            except Exception:
                pass
    if text is None:
        return u""
    return unicode(text).rstrip() + u"\n"

